
CREATE TABLE plan (
                      plan_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                      plan_name VARCHAR(30) NOT NULL,
                      max_tasks_per_dashboard INTEGER NOT NULL
                          CHECK (max_tasks_per_dashboard >= 0),
                      price NUMERIC(10, 2) NOT NULL CHECK (price >= 0),
                      active BOOLEAN NOT NULL DEFAULT TRUE
);

CREATE TABLE users (
                       user_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                       username VARCHAR(50) NOT NULL,
                       password_hash VARCHAR(255) NOT NULL,
                       created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE UNIQUE INDEX uq_users_username_lower
    ON users (LOWER(username));

CREATE TABLE dashboards (
                            dashboard_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                            user_id BIGINT NOT NULL REFERENCES users(user_id)
                                ON DELETE CASCADE,
                            dashboard_name VARCHAR(100) NOT NULL,
                            created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
                            UNIQUE (user_id, dashboard_name)
);

CREATE TABLE tasks (
                       task_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                       dashboard_id BIGINT NOT NULL REFERENCES dashboards(dashboard_id)
                           ON DELETE CASCADE,
                       title VARCHAR(200) NOT NULL,
                       description TEXT,
                       status VARCHAR(20) NOT NULL DEFAULT 'TODO'
                           CHECK (status IN ('TODO', 'IN_PROGRESS', 'COMPLETED')),
                       created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
                       updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE subscriptions (
                               subscription_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                               user_id BIGINT NOT NULL REFERENCES users(user_id)
                                   ON DELETE CASCADE,
                               plan_id BIGINT NOT NULL REFERENCES plan(plan_id)
                                   ON DELETE RESTRICT,
                               status VARCHAR(20) NOT NULL
                                   CHECK (status IN ('ACTIVE', 'ENDED')),
                               start_date TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
                               end_date TIMESTAMPTZ,
                               CHECK (
                                   (status = 'ACTIVE' AND end_date IS NULL)
                                       OR
                                   (status = 'ENDED' AND end_date IS NOT NULL
                                       AND end_date >= start_date)
                                   )
);

CREATE UNIQUE INDEX uq_subscriptions_one_active_per_user
    ON subscriptions (user_id)
    WHERE status = 'ACTIVE';

CREATE INDEX idx_dashboards_user_id ON dashboards(user_id);
CREATE INDEX idx_tasks_dashboard_id ON tasks(dashboard_id);
CREATE INDEX idx_subscriptions_plan_id ON subscriptions(plan_id);
